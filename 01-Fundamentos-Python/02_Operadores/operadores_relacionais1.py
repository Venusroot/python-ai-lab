

# atribuição =
n1 = 3
n2 = 2

# igualdade relacionais 
# tem como resposta: true ou false

# igualdade ==
res1 = (n1 == n2)
print (res1)

# diferente !=
res2 = (n1 != n2)
print (res2)

# menor <
res3 = (n1 < n2)
print (res3)

# maior >
res4 = (n1 > n2)
print (res4)

# menor ou igual <=
res5 = (n1 <= n2)
print (res5)

# maior ou igual >=
res6 = (n1 >= n2)
print (res6)




